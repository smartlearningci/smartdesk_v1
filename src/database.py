"""Persistência PostgreSQL em Docker; SQLite apenas para fixtures legadas isoladas.

As assinaturas de connect/initialize e as consultas dos serviços são preservadas.
DATABASE_URL é obrigatória em operação normal: nunca há fallback silencioso.
"""
import os
import sqlite3

SCHEMA = """
CREATE TABLE IF NOT EXISTS users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    secret TEXT NOT NULL,
    role TEXT NOT NULL CHECK (role IN ('colaborador','tecnico','responsavel'))
);
CREATE TABLE IF NOT EXISTS tickets (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL CHECK (length(trim(title)) > 0),
    description TEXT NOT NULL CHECK (length(trim(description)) > 0),
    category TEXT NOT NULL CHECK (category IN ('Equipamento','Software','Acessos')),
    state TEXT NOT NULL DEFAULT 'Aberto'
      CHECK (state IN ('Aberto','Em tratamento','Resolvido','Fechado')),
    creator_id INTEGER NOT NULL REFERENCES users(id),
    technician_id INTEGER REFERENCES users(id),
    resolution TEXT
);
"""

class Result:
    """Compatibilidade com cursor.lastrowid do SQLite."""
    def __init__(self, cursor, lastrowid=None):
        self.cursor = cursor
        self.lastrowid = lastrowid

    def fetchone(self):
        return self.cursor.fetchone()

    def fetchall(self):
        return self.cursor.fetchall()

    def __iter__(self):
        return iter(self.cursor)

class PostgresConnection:
    def __init__(self, url):
        import psycopg
        from psycopg.rows import dict_row
        self.connection = psycopg.connect(url, row_factory=dict_row)

    def execute(self, sql, params=()):
        # Consultas SQL do MVP usam marcadores SQLite (?).
        sql = sql.replace("?", "%s")
        is_insert = sql.lstrip().upper().startswith("INSERT INTO")
        if is_insert and "RETURNING" not in sql.upper():
            sql += " RETURNING id"
        cursor = self.connection.execute(sql, params)
        if is_insert:
            row = cursor.fetchone()
            return Result(cursor, row["id"])
        return Result(cursor)

    def commit(self):
        self.connection.commit()

    def rollback(self):
        self.connection.rollback()

    def __enter__(self):
        return self

    def __exit__(self, exc_type, exc, tb):
        try:
            if exc_type is None:
                self.commit()
            else:
                self.rollback()
        finally:
            self.connection.close()
        return False

def connect(path=None):
    """Um path explícito conserva testes SQLite; sem path usa PostgreSQL."""
    if path is not None:
        db = sqlite3.connect(path)
        db.row_factory = sqlite3.Row
        db.execute("PRAGMA foreign_keys=ON")
        return db
    url = os.getenv("DATABASE_URL")
    if not url:
        raise RuntimeError("DATABASE_URL obrigatória para a aplicação PostgreSQL")
    return PostgresConnection(url)

def initialize(db):
    """Cria as tabelas em falta, sem apagar nem substituir dados."""
    if isinstance(db, sqlite3.Connection):
        db.executescript("""
        CREATE TABLE IF NOT EXISTS users (
            id INTEGER PRIMARY KEY, name TEXT NOT NULL, email TEXT NOT NULL UNIQUE,
            secret TEXT NOT NULL,
            role TEXT NOT NULL CHECK(role IN ('colaborador','tecnico','responsavel'))
        );
        CREATE TABLE IF NOT EXISTS tickets (
            id INTEGER PRIMARY KEY,
            title TEXT NOT NULL CHECK(length(trim(title)) > 0),
            description TEXT NOT NULL CHECK(length(trim(description)) > 0),
            category TEXT NOT NULL CHECK(category IN ('Equipamento','Software','Acessos')),
            state TEXT NOT NULL DEFAULT 'Aberto'
              CHECK(state IN ('Aberto','Em tratamento','Resolvido','Fechado')),
            creator_id INTEGER NOT NULL REFERENCES users(id),
            technician_id INTEGER REFERENCES users(id),
            resolution TEXT
        );
        """)
    else:
        for statement in SCHEMA.split(";"):
            if statement.strip():
                db.execute(statement)
    db.commit()
