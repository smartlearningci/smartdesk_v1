"""Persistência V2: PostgreSQL no Compose; SQLite em fixtures legadas isoladas.

O adaptador mantém db.execute(), fetchone(), commit() e lastrowid utilizados
pelas regras existentes. Não modifica endpoints nem permissões.
"""
import os
import sqlite3


class PgCursor:
    """Compatibilidade com lastrowid usado após INSERT em users/tickets."""
    def __init__(self, cursor, inserted=False):
        self.cursor = cursor
        self.lastrowid = cursor.fetchone()["id"] if inserted else None

    def fetchone(self):
        return self.cursor.fetchone()

    def fetchall(self):
        return self.cursor.fetchall()

    def __iter__(self):
        return iter(self.cursor)


class PgConnection:
    def __init__(self, connection):
        self.connection = connection

    def execute(self, sql, params=()):
        # SQL legado usa '?' como marcador; psycopg usa '%s'.
        # As consultas existentes não contêm '?' literal.
        statement = sql.replace("?", "%s")
        normalized = statement.lstrip().upper()
        inserted = normalized.startswith(("INSERT INTO TICKETS(", "INSERT INTO USERS("))
        if inserted and "RETURNING" not in normalized:
            statement += " RETURNING id"
        cursor = self.connection.execute(statement, params)
        return PgCursor(cursor, inserted)

    def commit(self):
        self.connection.commit()

    def rollback(self):
        self.connection.rollback()

    def __enter__(self):
        return self

    def __exit__(self, exc_type, exc, tb):
        try:
            if exc_type:
                self.connection.rollback()
            else:
                self.connection.commit()
        finally:
            self.connection.close()


def connect(path=None):
    """Um caminho explícito mantém SQLite apenas para testes legados."""
    if path is not None:
        db = sqlite3.connect(path)
        db.row_factory = sqlite3.Row
        db.execute("PRAGMA foreign_keys=ON")
        return db
    url = os.getenv("DATABASE_URL")
    if not url:
        raise RuntimeError("DATABASE_URL não definida. Configure o .env do Docker Compose.")
    import psycopg
    from psycopg.rows import dict_row
    try:
        return PgConnection(psycopg.connect(url, row_factory=dict_row, connect_timeout=5))
    except psycopg.OperationalError as exc:
        raise RuntimeError("Não foi possível ligar ao PostgreSQL. Verifique o serviço db e o .env.") from exc


def initialize(db):
    """Inicialização repetível, sem eliminar dados nem migrar SQLite automaticamente."""
    if isinstance(db, sqlite3.Connection):
        db.executescript("""
        CREATE TABLE IF NOT EXISTS users (
            id INTEGER PRIMARY KEY, name TEXT NOT NULL, email TEXT NOT NULL UNIQUE,
            secret TEXT NOT NULL, role TEXT NOT NULL
              CHECK(role IN ('colaborador','tecnico','responsavel')));
        CREATE TABLE IF NOT EXISTS tickets (
            id INTEGER PRIMARY KEY,
            title TEXT NOT NULL CHECK(length(trim(title)) > 0),
            description TEXT NOT NULL CHECK(length(trim(description)) > 0),
            category TEXT NOT NULL CHECK(category IN ('Equipamento','Software','Acessos')),
            state TEXT NOT NULL DEFAULT 'Aberto'
              CHECK(state IN ('Aberto','Em tratamento','Resolvido','Fechado')),
            creator_id INTEGER NOT NULL REFERENCES users(id),
            technician_id INTEGER REFERENCES users(id), resolution TEXT);
        """)
    else:
        db.execute("""
        CREATE TABLE IF NOT EXISTS users (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            name TEXT NOT NULL, email TEXT NOT NULL UNIQUE, secret TEXT NOT NULL,
            role TEXT NOT NULL CHECK(role IN ('colaborador','tecnico','responsavel')))
        """)
        db.execute("""
        CREATE TABLE IF NOT EXISTS tickets (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            title TEXT NOT NULL CHECK(length(btrim(title)) > 0),
            description TEXT NOT NULL CHECK(length(btrim(description)) > 0),
            category TEXT NOT NULL CHECK(category IN ('Equipamento','Software','Acessos')),
            state TEXT NOT NULL DEFAULT 'Aberto'
                CHECK(state IN ('Aberto','Em tratamento','Resolvido','Fechado')),
            creator_id INTEGER NOT NULL REFERENCES users(id),
            technician_id INTEGER REFERENCES users(id), resolution TEXT)
        """)
    db.commit()
